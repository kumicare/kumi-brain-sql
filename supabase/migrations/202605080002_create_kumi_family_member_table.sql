-- Create the Kumi family member table.

begin;

create table if not exists kumi_core.kumi_family_member (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  member_type smallint not null,
  birthday date,
  gender smallint,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table kumi_core.kumi_family_member is 'Family members known to Kumi Brain, including people and pets.';
comment on column kumi_core.kumi_family_member.id is 'Primary key generated by PostgreSQL UUID function gen_random_uuid().';
comment on column kumi_core.kumi_family_member.name is 'Family member display name.';
comment on column kumi_core.kumi_family_member.member_type is 'Member type code: 0=human, 1=pets, 2=relative.';
comment on column kumi_core.kumi_family_member.birthday is 'Birthday in calendar date format; nullable when unknown.';
comment on column kumi_core.kumi_family_member.gender is 'Gender code: 0=male, 1=female.';
comment on column kumi_core.kumi_family_member.description is 'Free-form notes for OpenClaw or app display.';
comment on column kumi_core.kumi_family_member.created_at is 'Record creation timestamp.';
comment on column kumi_core.kumi_family_member.updated_at is 'Record last update timestamp; automatic refresh trigger can be added later.';

commit;
